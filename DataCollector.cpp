/*
=========================================================
 Модуль DataCollector

 Данный файл отвечает за сбор входных данных из интерфейса
 программы (MainWindow) и формирование одномерного массива
 параметров, используемого для дальнейших вычислений.

 Основная задача модуля:
 - считать значения, выбранные пользователем в интерфейсе;
 - привести их к числовому виду;
 - сформировать структурированный массив данных.

 Формируемый массив содержит 9 элементов:
 0 – вариант схемы (1 или 2);
 1 – количество значащих тетрад (1..7);
 2 – режим работы (0 – "Полный цикл", 1 – "Пара чисел");
 3 – число A;
 4 – число B;
 5 – входной перенос (0 или 1);
 6 – номер тетрады с ошибкой (-1, если ошибки нет);
 7 – вид ошибки (0 – "Сбой", 1 – "Отказ");
 8 – константа (0 или 1).

 Принцип работы:
 1. Получение данных из элементов интерфейса (кнопки,
    поля ввода, выпадающие списки).
 2. Проверка и преобразование данных (например, строк в числа).
 3. Формирование одномерного массива (QVector<int>).
 4. Возврат массива в вызывающий код (MainWindow).

 Разделение логики:
 - MainWindow отвечает за отображение интерфейса;
 - DataCollector отвечает за извлечение данных из интерфейса;
 - MassScheme отвечает за обработку данных и построение массива.

 Такое разделение делает код более понятным,
 структурированным и удобным для изменения.
=========================================================
*/

#include "DataCollector.h"
#include "mainwindow.h"
#include "ui_mainwindow.h"

QVector<int> DataCollector::collect(MainWindow *window)
{
    QVector<int> data(9);

    Ui::MainWindow *ui = window->getUI();

    // 0 – вариант схемы
    data[0] = ui->VariantBtn->currentIndex() + 1;

    // 1 – количество тетрад
    data[1] = ui->comboTetrads->currentText().toInt();

    // 2 – режим работы
    if (ui->btnFullCycle->isChecked())
        data[2] = 0;
    else
        data[2] = 1;

    // 3 – число A
    data[3] = ui->btnA->text().toInt();

    // 4 – число B
    data[4] = ui->btnB->text().toInt();

    // 5 – входной перенос
    data[5] = ui->btnCarry->currentText().toInt();

    // 6 – номер тетрады ошибки
    QString errorText = ui->comboError->currentText();

    if (errorText == "Нет")
        data[6] = -1;
    else if (errorText == "Знак")
        data[6] = ui->comboTetrads->currentText().toInt();
    else
        data[6] = errorText.toInt();

    // 7 – вид ошибки
    if (ui->btnFail->isChecked())
        data[7] = 0;
    else
        data[7] = 1;

    // 8 – константа
    if (ui->btnConst0->isChecked())
        data[8] = 0;
    else
        data[8] = 1;

    return data;
}
